"""Bangla glyphs for the pdfLaTeX fallback build of the paper (paper/bn/glyphs.pdf + paper/bn/glyphs.tex).

pdfLaTeX cannot shape Bengali, so every distinct \\bn{...} string in paper/main.tex is typeset once with XeLaTeX
(Noto Serif Bengali, as in the primary build) on its own page of bn/glyphs.pdf. Each page box runs from 0.45em below
to 1.2em above the baseline, measured in the main font, so main.tex can place it at text size with
\\raisebox{-0.45em}{\\includegraphics[totalheight=1.65em,...]}. bn/glyphs.tex maps the MD5 of each string's UTF-8
bytes (what pdfTeX's \\pdfmdfivesum computes) to its page. Rerun after adding or changing a \\bn{...} string.
    python tools/bn_glyphs.py
"""

from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
OUT = PAPER / "bn"

DOC = r"""\documentclass[multi=bnbox,border=0pt]{standalone}
\usepackage{fontspec}
\setmainfont{texgyretermes}[Extension=.otf, UprightFont=*-regular]
\newfontfamily\bengalifont{NotoSerifBengali-Regular.ttf}[Path=%(fonts)s/, Script=Bengali, Scale=MatchLowercase]
\newenvironment{bnbox}{}{}
\begin{document}
%(boxes)s
\end{document}
"""


def strings() -> list[str]:
    tex = (PAPER / "main.tex").read_text(encoding="utf-8")
    tex = re.sub(r"(?m)(?<!\\)%.*$", "", tex)  # ignore comments
    seen: dict[str, None] = {}
    for s in re.findall(r"\\bn\{([^{}]*)\}", tex):
        seen.setdefault(s, None)
    return list(seen)


def main() -> None:
    items = strings()
    if not items:
        raise SystemExit("no \\bn{...} strings found in paper/main.tex")
    boxes = "\n".join(
        r"\begin{bnbox}\rule[-0.45em]{0pt}{1.65em}{\bengalifont %s}\end{bnbox}" % s for s in items
    )
    OUT.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "glyphs.tex"
        fonts = (PAPER / "fonts").as_posix()
        src.write_text(DOC % {"fonts": fonts, "boxes": boxes}, encoding="utf-8")
        subprocess.run(
            ["xelatex", "-interaction=nonstopmode", "-halt-on-error", "glyphs.tex"],
            cwd=tmp, check=True, stdout=subprocess.DEVNULL,
        )
        shutil.copyfile(Path(tmp) / "glyphs.pdf", OUT / "glyphs.pdf")
    lines = ["% Generated by tools/bn_glyphs.py: MD5 of the UTF-8 string -> page of bn/glyphs.pdf."]
    for page, s in enumerate(items, start=1):
        key = hashlib.md5(s.encode("utf-8")).hexdigest().upper()
        lines.append(r"\expandafter\def\csname bn@%s\endcsname{%d}" % (key, page))
    (OUT / "glyphs.tex").write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"{len(items)} strings -> {OUT / 'glyphs.pdf'}")


if __name__ == "__main__":
    main()
