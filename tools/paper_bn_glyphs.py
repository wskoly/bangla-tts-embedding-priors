"""Bengali strings for the paper as small vector PDFs, so main.tex compiles with pdflatex (arXiv has no XeLaTeX).

Each string is set in Noto Serif Bengali (SIL OFL 1.1, paper/fonts/) at a fixed size on a fixed-height canvas with a
fixed baseline, so `\\bn{key}` in main.tex (height 1.55em, lowered 0.5em) lines up with the running text.
Conversions shown in the paper are produced by src.bnrep.reps, not typed by hand.
    python tools/paper_bn_glyphs.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib import font_manager  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.bnrep.reps import convert  # noqa: E402

FONT = ROOT / "paper/fonts/NotoSerifBengali-Regular.ttf"
OUT = ROOT / "paper/bn"
SIZE_PT, HEIGHT, BASELINE = 10.0, 1.55, 0.32  # canvas height in em; baseline as a fraction of the canvas

STRINGS = {"ca": "চ", "ka": "ক", "cha": "ছ", "kha": "খ", "a": "অ", "aa": "আ", "aasign": "া", "hasanta": "্",
           "aricha": "আরিচা", "arika": "আরিকা", "kolom": "কলম", "chobi": "ছবি", "boi": "বই", "bidda": "বিদ্যা",
           "gyan": "জ্ঞান", "shopno": "স্বপ্ন", "chokh": "চোখ", "ga": "গ", "ba": "ব", "ha": "হ"}
for rep, key in (("BN-G-iv", "chokhiv"), ("BN-G-iv-vm", "chokhvm"), ("BN-G-iv-vm-asp", "chokhasp"),
                 ("BN-G-iv", "kolomiv")):
    STRINGS[key] = convert(rep, "কলম" if key.startswith("kolom") else "চোখ").text


def render(key: str, text: str, prop) -> None:
    h_in = SIZE_PT * HEIGHT / 72
    fig = plt.figure(figsize=(4, h_in))
    t = fig.text(0, BASELINE, text, fontproperties=prop, fontsize=SIZE_PT, va="baseline")
    fig.canvas.draw()
    w_px = t.get_window_extent().width
    fig.set_size_inches(w_px / fig.dpi + 1.0 / 72, h_in)
    t.set_x((0.5 / 72) / fig.get_size_inches()[0])
    fig.savefig(OUT / f"{key}.pdf", transparent=True)
    plt.close(fig)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    prop = font_manager.FontProperties(fname=str(FONT))
    plt.rcParams["pdf.fonttype"] = 42
    for k, s in STRINGS.items():
        render(k, s, prop)
    (OUT / "README.txt").write_text("Generated by tools/paper_bn_glyphs.py (Noto Serif Bengali, SIL OFL 1.1).\n"
                                    + "\n".join(f"{k}\t{s}" for k, s in STRINGS.items()) + "\n", encoding="utf-8")
    print(f"{len(STRINGS)} glyph PDFs -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
