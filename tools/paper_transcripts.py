"""Appendix table of example transcripts (illustration, not evidence).

Sentence rule, fixed in tools/build_samples_page.py and used unchanged here: test_seen sentences with 3-7 s of
speech, ordered by sha256(utt_id + "samples-v1"); the first sentence of each corpus is shown. For that sentence the
table lists the Whisper transcript and CER of seven arms, from the seed-666 run at 3,000 updates (the same runs that
enter the paper's means).
    python tools/paper_transcripts.py      # -> paper/transcripts.tex
"""

from __future__ import annotations

import csv
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
os.environ["DATA_PROFILE"] = "rasa_bn_v1"  # analyze_c1 needs the Rasa manifest; analyze_c3 reads run dirs only
import analyze_c1 as c1  # noqa: E402
import analyze_c3 as c3  # noqa: E402
from build_samples_page import pick  # noqa: E402

ASR = "tugstugi_bengaliai-asr_whisper-medium"
OUT = ROOT / "paper/transcripts.tex"
ARMS = [  # (arm, rows), in the order of the paper's argument: fresh Bengali, fresh/scrambled Latin, pretrained Latin
    ("BN-G-matched", "fresh"), ("BN-G-iv-vm-asp", "fresh"), ("LAT-P-reinit", "fresh"), ("LAT-P-rand", "scrambled"),
    ("LAT-G-det", "pretrained"), ("LAT-G-asp", "pretrained"), ("LAT-P", "pretrained")]
CORPORA = {"slr37": ("SLR37", c3), "rasa": ("Rasa", c1)}
TEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
       "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def esc(s: str) -> str:
    return "".join(TEX.get(ch, ch) for ch in s)


def asr_row(run: Path, utt: str) -> dict:
    with open(run / f"eval/u3000/test_seen/asr_{ASR}.tsv", encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
            if r["utt_id"] == utt:
                return r
    raise KeyError(f"{utt} not in {run}")


def main() -> int:
    L = ["% Generated by tools/paper_transcripts.py. Do not edit by hand.",
         r"\begin{tabular}{@{}l l >{\raggedright\arraybackslash}p{9.4cm} r@{}}", r"\toprule",
         r"Arm & Rows & Whisper transcript & CER (\%) \\"]
    for corpus, (label, mod) in CORPORA.items():
        rand, _, text, _ = pick(corpus)
        utt = rand[0]
        L += [r"\midrule", rf"\multicolumn{{4}}{{@{{}}l}}{{\emph{{{label}}}, \code{{{esc(utt)}}}}} \\",
              rf"\emph{{reference}} & & \bn{{{esc(text[utt])}}} & \\"]
        for arm, rows in ARMS:
            run = mod.run_dirs(arm)[0]
            assert run.name.endswith("__s666"), run
            r = asr_row(run, utt)
            L.append(rf"\arm{{{arm}}} & {rows} & \bn{{{esc(r['hyp'])}}} & {100 * float(r['cer']):.1f} \\")
    L += [r"\bottomrule", r"\end{tabular}", ""]
    OUT.write_text("\n".join(L), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
